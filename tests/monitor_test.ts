Deno.test("monitor percent-encodes action paths and omits a missing log", async () => {
  const temporary = await Deno.makeTempDir({ prefix: "mci action path " });
  const workspace = `${temporary}/mci | '$ test space`;
  try {
    await Deno.mkdir(workspace);
    await writeStatus(workspace, completed("pass", 0));
    let menu = await renderMonitor(workspace);
    assert(menu.startsWith("mci '$ test space: PASS | "));
    assert(menu.split("\n")[2]?.endsWith(" '$ test space"));
    assert(!menu.split("\n")[2]?.includes("|"));
    assert(menu.includes("Open repository"));
    assert(menu.includes("%20"));
    assert(menu.includes("%7C"));
    assert(!menu.includes(`param1=${workspace}`));
    assert(!menu.includes("Open log"));

    await Deno.writeTextFile(logPath(workspace), "untrusted | refresh=true\n");
    menu = await renderMonitor(workspace);
    assert(menu.includes("Open log"));
    assert(menu.includes("param1=-a param2=TextEdit"));
    assert(!menu.includes("untrusted"));
  } finally {
    await Deno.remove(temporary, { recursive: true });
  }
});

Deno.test("installer creates one executable plugin and preserves unrelated files", async () => {
  await inWorkspace(async (workspace) => {
    const pluginDirectory = `${workspace}/plugins`;
    await Deno.mkdir(pluginDirectory);
    await Deno.writeTextFile(`${pluginDirectory}/unrelated.1h.sh`, "keep\n");

    const installed = unwrap(
      await installMonitor({
        workspace,
        source: Deno.cwd(),
        pluginDirectory,
        denoPath: Deno.execPath(),
      }),
    );
    assert(pluginPattern.test(baseName(installed.path)), baseName(installed.path));
    equal(installed.path, `${pluginDirectory}/${baseName(installed.path)}`);
    equal(installed.removedLegacy, false);
    equal(await Deno.readTextFile(`${pluginDirectory}/unrelated.1h.sh`), "keep\n");
    const info = await Deno.stat(installed.path);
    assert((info.mode ?? 0) & 0o111, "plugin must be executable");
    equal(await listNames(pluginDirectory), [
      baseName(installed.path),
      "unrelated.1h.sh",
    ]);
    const body = await Deno.readTextFile(installed.path);
    assert(body.includes(markerFor(workspace)));
    assert(body.includes(`cd '${workspace}' || exit 1`));
  });
});

Deno.test("installer rejects unrelated collisions and permits its own reinstall", async () => {
  await inWorkspace(async (workspace) => {
    const pluginDirectory = `${workspace}/plugins`;
    await Deno.mkdir(pluginDirectory);
    const options = {
      workspace,
      source: Deno.cwd(),
      pluginDirectory,
      denoPath: Deno.execPath(),
    };
    const first = unwrap(await installMonitor(options));
    unwrap(await installMonitor(options));
    assert(await exists(first.path));

    const foreign = "#!/bin/sh\necho unrelated\n";
    await Deno.writeTextFile(first.path, foreign);
    const collision = await installMonitor(options);
    assert(!collision.ok);
    assert(collision.error.includes(baseName(first.path)));
    equal(await Deno.readTextFile(first.path), foreign);
    equal(await listNames(pluginDirectory), [baseName(first.path)]);
  });
});

Deno.test("installer gives two workspaces two plugins that show their own state", async () => {
  await inWorkspace(async (workspace) => {
    const alpha = `${workspace}/alpha repo`;
    const beta = `${workspace}/beta repo`;
    await Promise.all([Deno.mkdir(alpha), Deno.mkdir(beta)]);
    await writeStatus(alpha, completed("pass", 0));
    await writeStatus(beta, completed("fail", 7));
    const pluginDirectory = `${workspace}/plugins`;
    const install = (target: string) =>
      installMonitor({
        workspace: target,
        source: Deno.cwd(),
        pluginDirectory,
        denoPath: Deno.execPath(),
      });
    const first = unwrap(await install(alpha));
    const second = unwrap(await install(beta));
    assert(first.path !== second.path);
    assert(pluginPattern.test(baseName(first.path)), baseName(first.path));
    assert(pluginPattern.test(baseName(second.path)), baseName(second.path));
    assert(baseName(first.path).startsWith("mci-alpha-repo-"));
    assert(baseName(second.path).startsWith("mci-beta-repo-"));
    equal((await listNames(pluginDirectory)).length, 2);

    const [alphaRun, betaRun] = await Promise.all([
      runPlugin(first.path, workspace),
      runPlugin(second.path, workspace),
    ]);
    assert(alphaRun.success, alphaRun.stderr);
    assert(betaRun.success, betaRun.stderr);
    assert(alphaRun.stdout.startsWith("alpha repo: PASS"), alphaRun.stdout);
    assert(betaRun.stdout.startsWith("beta repo: FAIL"), betaRun.stdout);
    assert(alphaRun.stdout.includes(`Repository: ${alpha}`));
    assert(betaRun.stdout.includes(`Repository: ${beta}`));
  });
});

