Deno.test("installed plugin handles shell punctuation in source and workspace paths", async () => {
  await inWorkspace(async (parent) => {
    const source = `${parent}/source, | '$\` folder`;
    await Deno.mkdir(`${source}/scripts`, { recursive: true });
    await Deno.mkdir(`${source}/src`, { recursive: true });
    await Promise.all([
      Deno.copyFile("deno.json", `${source}/deno.json`),
      Deno.copyFile("scripts/monitor.ts", `${source}/scripts/monitor.ts`),
      Deno.copyFile("src/ci.ts", `${source}/src/ci.ts`),
      Deno.copyFile("src/command.ts", `${source}/src/command.ts`),
      Deno.copyFile("src/result.ts", `${source}/src/result.ts`),
      Deno.copyFile("src/process.ts", `${source}/src/process.ts`),
    ]);
    const workspace = `${parent}/work, | '$\` area`;
    await Deno.mkdir(workspace);
    const pluginDirectory = `${parent}/plugin output`;
    const installed = unwrap(
      await installMonitor({
        workspace,
        source,
        pluginDirectory,
        denoPath: Deno.execPath(),
      }),
    );
    assert(pluginPattern.test(baseName(installed.path)), baseName(installed.path));
    const run = await runPlugin(installed.path, parent);
    assert(run.success, run.stderr);
    assert(run.stdout.startsWith("work, '$\` area: NO RUNS"), run.stdout);
    assert(run.stdout.split("\n")[2]?.startsWith("Repository: /"), run.stdout);
  });
});

