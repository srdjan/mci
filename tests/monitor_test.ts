Deno.test("installer refuses the internal cache through a parent symlink", () =>
  inWorkspace(async (workspace) => {
    const fixtureHome = `${workspace}/home`;
    const support = `${fixtureHome}/Library/Application Support/SwiftBar`;
    await Deno.mkdir(`${support}/Plugins`, { recursive: true });
    const alias = `${workspace}/alias`;
    await Deno.symlink(support, alias);
    const output = await new Deno.Command(Deno.execPath(), {
      args: [
        "run",
        "--quiet",
        "--permission-set=mci",
        "--config",
        `${Deno.cwd()}/deno.json`,
        `${Deno.cwd()}/scripts/install-monitor.ts`,
        workspace,
        `${alias}/Plugins`,
      ],
      env: { HOME: fixtureHome },
      stdout: "piped",
      stderr: "piped",
    }).output();
    assert(!output.success);
    assert(new TextDecoder().decode(output.stderr).includes("internal plugin cache"));
    const leftovers = (await listNames(`${support}/Plugins`)).filter((name) =>
      /^mci-.*\.5s\.sh$/.test(name)
    );
    equal(leftovers, []);
  }));

Deno.test("installer CLI rejects a relative workspace and extra arguments", () =>
  inWorkspace(async (workspace) => {
    const run = async (...args: string[]) => {
      const output = await new Deno.Command(Deno.execPath(), {
        args: [
          "run",
          "--quiet",
          "--permission-set=mci",
          "--config",
          `${Deno.cwd()}/deno.json`,
          `${Deno.cwd()}/scripts/install-monitor.ts`,
          ...args,
        ],
        stdout: "piped",
        stderr: "piped",
      }).output();
      return { code: output.code, stderr: new TextDecoder().decode(output.stderr) };
    };
    const relative = await run("relative/path");
    equal(relative.code, 2);
    assert(relative.stderr.includes("workspace must be an absolute path"));
    const extra = await run(workspace, `${workspace}/plugins`, "extra");
    equal(extra.code, 2);
    assert(extra.stderr.includes("Usage:"));
    assert(!await exists(`${workspace}/plugins`));
  }));
